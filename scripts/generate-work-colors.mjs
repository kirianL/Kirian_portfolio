/**
 * Extracts the dominant colour of every work capture so the grid reveal can
 * paint its loading tiles in that colour instead of a neutral gray.
 *
 * Run with `npm run work:colors` after adding or replacing an image in
 * `public/work`. The output is committed; nothing is computed in the browser
 * before the photo arrives.
 */
import { chromium } from "playwright-core";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve("public/work");
const OUT = path.resolve("src/data/workColors.ts");
const IMAGE_EXTENSIONS = new Set([".png", ".webp"]);

function collect(dir, prefix = "") {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(dir, entry.name);
    const key = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) files.push(...collect(absolute, key));
    else if (IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase()))
      files.push({ absolute, key: `/work${key}` });
  }
  return files;
}

const files = collect(ROOT).sort((a, b) => a.key.localeCompare(b.key));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
const colors = {};

for (const { absolute, key } of files) {
  const mime = path.extname(absolute).toLowerCase() === ".webp" ? "image/webp" : "image/png";
  const base64 = fs.readFileSync(absolute).toString("base64");
  const result = await page.evaluate(
    async ({ base64, mime }) => {
      const image = new Image();
      image.src = `data:${mime};base64,${base64}`;
      await image.decode();

      const SIZE = 96;
      const canvas = document.createElement("canvas");
      canvas.width = SIZE;
      canvas.height = SIZE;
      const ctx = canvas.getContext("2d", { willReadFrequently: true });
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(image, 0, 0, SIZE, SIZE);
      const { data } = ctx.getImageData(0, 0, SIZE, SIZE);

      // Quantise to 5 bits per channel and keep the most frequent bucket. A
      // screenshot is mostly its own background, so this lands closer to the
      // photo than a global average dulled by text and UI chrome.
      const buckets = new Map();
      let sumR = 0;
      let sumG = 0;
      let sumB = 0;
      let total = 0;

      for (let i = 0; i < data.length; i += 4) {
        if (data[i + 3] < 16) continue;
        const r = data[i];
        const g = data[i + 1];
        const b = data[i + 2];
        sumR += r;
        sumG += g;
        sumB += b;
        total++;
        const key = ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3);
        let bucket = buckets.get(key);
        if (!bucket) {
          bucket = { count: 0, r: 0, g: 0, b: 0 };
          buckets.set(key, bucket);
        }
        bucket.count++;
        bucket.r += r;
        bucket.g += g;
        bucket.b += b;
      }

      if (!total) return null;
      let winner = null;
      for (const bucket of buckets.values()) {
        if (!winner || bucket.count > winner.count) winner = bucket;
      }

      const channel = (value) => Math.round(value / winner.count);
      const [dr, dg, db] = [channel(winner.r), channel(winner.g), channel(winner.b)];
      const dominant = `#${[dr, dg, db]
        .map((n) => n.toString(16).padStart(2, "0"))
        .join("")}`;
      const average = `#${[sumR / total, sumG / total, sumB / total]
        .map((n) => Math.round(n).toString(16).padStart(2, "0"))
        .join("")}`;

      // A loading tile must never read as an empty white box. A near-white,
      // near-neutral dominant colour carries no usable hue, so the page falls
      // back to the dark surface instead of tinting the mosaic light gray.
      const luma = (0.299 * dr + 0.587 * dg + 0.114 * db) / 255;
      const chroma = (Math.max(dr, dg, db) - Math.min(dr, dg, db)) / 255;
      const placeholder = luma > 0.72 && chroma < 0.16 ? "#141414" : dominant;
      return { dominant, average, placeholder };
    },
    { base64, mime },
  );

  if (!result) {
    console.warn(`skip ${key}: no opaque pixels`);
    continue;
  }
  colors[key] = result.placeholder;
  console.log(
    `${key} -> ${result.placeholder} (dominant ${result.dominant}, avg ${result.average})`,
  );
}

await browser.close();

const body = Object.entries(colors)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");

const source = `/**
 * Generated by \`npm run work:colors\` (scripts/generate-work-colors.mjs).
 * Do not edit by hand.
 *
 * Each value is the most frequent colour of the capture, sampled from a 96x96
 * reduction, or the page surface (#141414) when that colour is near-white.
 * GridRevealImage paints its loading tiles with it so a work detail never
 * flashes a neutral white box before the screenshot arrives.
 */
export const WORK_IMAGE_COLORS: Record<string, string> = {
${body}
};

/** Look up the placeholder colour of a work image by its public path. */
export function workImageColor(src?: string | null): string | undefined {
  if (!src) return undefined;
  return WORK_IMAGE_COLORS[src];
}
`;

fs.writeFileSync(OUT, source);
console.log(`\nwrote ${Object.keys(colors).length} colours to ${path.relative(process.cwd(), OUT)}`);
